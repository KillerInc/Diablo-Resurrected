"""Register private painted views and gather their RGB into canonical cells.

The native owner map determines which source pixel receives a sample. A source
pixel receives exactly one deterministic authoring sample, even when repeated.
Native alpha, frame numbering and atlas geometry are never regenerated by AI.
Requires numpy, Pillow and opencv-python-headless. No game-directory writes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS=None


def register(reference,art,cv2):
    """Map painted RGB onto the unchanged reference projection, not vice versa."""
    art=art.convert('RGB').resize(reference.size,Image.Resampling.LANCZOS)
    width=min(1000,reference.width);height=round(reference.height*width/reference.width)
    size=(width,height)
    def grey(image):
        rgb=np.asarray(image.convert('RGB').resize(size,Image.Resampling.LANCZOS))
        return cv2.GaussianBlur(cv2.cvtColor(rgb,cv2.COLOR_RGB2GRAY),(0,0),1.5)
    flow=cv2.calcOpticalFlowFarneback(grey(reference),grey(art),None,.5,5,41,5,7,1.5,0)
    flow=cv2.resize(flow,reference.size)
    flow[:,:,0]*=reference.width/width;flow[:,:,1]*=reference.height/height
    y,x=np.mgrid[:reference.height,:reference.width].astype(np.float32)
    mapped=cv2.remap(np.asarray(art),x+flow[:,:,0],y+flow[:,:,1],
                     cv2.INTER_LINEAR,borderMode=cv2.BORDER_REFLECT)
    distance=np.linalg.norm(flow,axis=2)
    return mapped,dict(displacement_p50=float(np.percentile(distance,50)),
                       displacement_p99=float(np.percentile(distance,99)),
                       displacement_max=float(distance.max()))


def gather(owners,rgb,allowed,cell,pixel_mask=None):
    """Prefer a frame's most complete occurrence; never average locations."""
    address=owners.ravel().astype(np.int64)-1
    valid=(address>=0)&np.isin(address//(cell*cell),list(allowed))
    if pixel_mask is not None:valid&=pixel_mask.ravel()
    positions=np.flatnonzero(valid)
    selected=address[positions];source_pixel=selected%(cell*cell)
    yy,xx=np.divmod(positions,owners.shape[1]);sy,sx=np.divmod(source_pixel,cell)
    stride=owners.shape[1]+2*cell;area=stride*(owners.shape[0]+2*cell)
    occurrence=selected//(cell*cell)*area+(yy-sy+cell)*stride+(xx-sx+cell)
    _,inverse,counts=np.unique(occurrence,return_inverse=True,return_counts=True)
    order=np.lexsort((positions,-counts[inverse],selected))
    unique,first=np.unique(selected[order],return_index=True)
    return unique,rgb.reshape(-1,3)[positions[order[first]]],int(len(positions)-len(unique))


def occurrence_mask(owners,layers,rect,source_cells,cell,density):
    """Select one whole native object occurrence, not unrelated repeats."""
    cells={tuple(c[:2]) for c in source_cells};result=np.zeros(owners.shape,dtype=bool)
    yy,xx=np.mgrid[:cell,:cell]
    for l in layers:
        if tuple(l['cell']) not in cells:continue
        x=(l['world'][0]-rect[0])*density;y=(l['world'][1]-rect[1])*density
        x0,y0=max(0,x),max(0,y);x1,y1=min(owners.shape[1],x+cell),min(owners.shape[0],y+cell)
        if x1<=x0 or y1<=y0:continue
        sx,sy=x0-x,y0-y
        address=1+l['frame']*cell*cell+yy[sy:sy+y1-y0,sx:sx+x1-x0]*cell+xx[sy:sy+y1-y0,sx:sx+x1-x0]
        result[y0:y1,x0:x1]|=owners[y0:y1,x0:x1]==address
    return result


def write_samples(atlas,addresses,rgb,cell,rows):
    frame=addresses//(cell*cell);pixel=addresses%(cell*cell)
    col,row=np.divmod(frame-1,rows)
    y=row*cell+pixel//cell;x=col*cell+pixel%cell
    if np.any(frame<1) or np.any(x>=atlas.shape[1]) or np.any(y>=atlas.shape[0]):
        raise ValueError('Owner address outside native atlas')
    if np.any(atlas[y,x,3]!=255):raise ValueError('Only opaque owner pixels can be painted')
    atlas[y,x,:3]=rgb


def build(args):
    if args.output.exists():raise ValueError('Use a new output directory')
    if args.dependencies:sys.path.insert(0,str(args.dependencies.resolve()))
    import cv2
    plan=json.loads(args.plan.read_text());project=Path(plan['project'])
    meta=json.loads((project/'project.json').read_text());cell=meta['cell'];rows=meta['rows']
    base=Image.open(project/'base-atlas.png').convert('RGBA')
    initial=Image.open(plan.get('initial_atlas',project/'base-atlas.png')).convert('RGBA')
    if initial.size!=base.size:raise ValueError('Initial atlas geometry changed')
    native=np.asarray(base);atlas=np.asarray(initial).copy()
    if not np.array_equal(native[:,:,3],atlas[:,:,3]):raise ValueError('Initial atlas alpha changed')
    args.output.mkdir(parents=True);reports=[]
    painted=np.zeros((meta['columns']*rows+1)*cell*cell,dtype=bool)
    if plan.get('initial_coverage'):
        existing=np.load(plan['initial_coverage'])['authored']
        if existing.shape!=painted.shape:raise ValueError('Initial coverage geometry changed')
        painted[:]=existing
    previous_authoring=painted.copy()
    for f in plan.get('reset_coverage_frames',[]):
        if not 1<=f<=meta['columns']*rows:raise ValueError('Invalid reassigned frame')
        painted[f*cell*cell:(f+1)*cell*cell]=False
    claimed=np.zeros_like(painted);registration_cache={}
    for item in plan['views']:
        region=Path(item['region']);record=json.loads((region/'region.json').read_text())
        reference=Image.open(region/'reference.png').convert('RGBA')
        if hashlib.sha256(reference.tobytes()).hexdigest()!=record['reference_sha256']:
            raise ValueError('Reference changed: '+item['id'])
        owners_path=region/'owners.npz'
        if hashlib.sha256(owners_path.read_bytes()).hexdigest()!=record['owners_sha256']:
            raise ValueError('Owner map changed: '+item['id'])
        owners=np.load(owners_path)['owners'];allowed=set(item['frames'])
        if not allowed or min(allowed)<1 or max(allowed)>meta['columns']*rows:
            raise ValueError('Invalid frame selection')
        cache_key=(str(region.resolve()),str(Path(item['art']).resolve()))
        if cache_key not in registration_cache:
            registration_cache[cache_key]=register(reference,Image.open(item['art']),cv2)
        mapped,stats=registration_cache[cache_key]
        mask=occurrence_mask(owners,meta['layers'],record['rect'],item['source_cells'],cell,meta['density']) if 'source_cells' in item else None
        addresses,rgb,repeated=gather(owners,mapped,allowed,cell,mask)
        # Explicit view order is authoring priority. Later variants only fill
        # pixels not already authored, preserving shared clean/poisoned pieces.
        keep=~(claimed if plan.get('replace_existing') else painted)[addresses]
        write_samples(atlas,addresses[keep],rgb[keep],cell,rows)
        painted[addresses[keep]]=True
        claimed[addresses[keep]]=True
        preview=Image.fromarray(mapped);preview.thumbnail((1400,1000))
        preview.save(args.output/(item['id']+'-registered.png'))
        reports.append(dict(id=item['id'],source_samples=int(keep.sum()),
                            selected_frames=sorted(allowed),repeated_view_samples=repeated,**stats))
        print(item['id'],int(keep.sum()),flush=True)
    if not np.array_equal(native[:,:,3],atlas[:,:,3]):raise AssertionError('Alpha changed')
    hidden=native[:,:,3]==0
    if not np.array_equal(native[hidden],atlas[hidden]):raise AssertionError('Hidden pixels changed')
    Image.fromarray(atlas).save(args.output/'town.png')
    # Reassignment unlocks previous samples for replacement; it does not erase
    # prior authoring in pixels untouched by this pass. Coverage is provenance,
    # not an artistic approval signal.
    np.savez_compressed(args.output/'authored-addresses.npz',authored=painted|previous_authoring)
    changed=np.any(native[:,:,:3]!=atlas[:,:,:3],axis=2)
    changed_frames=[]
    for f in range(1,meta['columns']*rows+1):
        c,r=divmod(f-1,rows)
        if changed[r*cell:(r+1)*cell,c*cell:(c+1)*cell].any():changed_frames.append(f)
    result=dict(format='d1r.town-art-assembly-v1',views=reports,changed_frames=changed_frames,
                changed_visible_pixels=int(changed.sum()),alpha_exact=True,hidden_rgba_exact=True,
                frame_count=meta['columns']*rows,atlas_size=list(base.size),
                repeated_source_policy='one canonical sample; first selected view wins',
                native_map_changed=False,installed=False)
    (args.output/'assembly.json').write_text(json.dumps(result,indent=2))
    print(json.dumps({k:v for k,v in result.items() if k not in ('views','changed_frames')}))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('plan',type=Path);p.add_argument('output',type=Path)
    p.add_argument('--dependencies',type=Path)
    build(p.parse_args())
